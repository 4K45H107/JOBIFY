const words = (text: string) =>
  text
    .toLowerCase()
    .split(/[\s,/().-]+/)
    .filter(Boolean);

/**
 * Options matching what's typed from the front: those that start with it first, then those with a
 * later word that starts with it ("king" finds "United Kingdom"). Matches in the middle of a word
 * ("ban" in "Albania") are left out. Case doesn't matter; already chosen values are left out.
 */
export function matchSuggestions(
  query: string,
  options: readonly string[],
  { limit = 8, exclude = [] }: { limit?: number; exclude?: readonly string[] } = {},
): string[] {
  const q = query.trim().toLowerCase();
  const skip = new Set(exclude.map((e) => e.toLowerCase()));
  const seen = new Set<string>();
  const ranked: [number, string][] = [];
  for (const option of options) {
    const key = option.toLowerCase();
    if (skip.has(key) || seen.has(key)) continue;
    seen.add(key);
    if (!q) {
      ranked.push([2, option]);
      continue;
    }
    if (key === q) continue;
    const rank = key.startsWith(q) ? 0 : words(option).some((w) => w.startsWith(q)) ? 1 : -1;
    if (rank >= 0) ranked.push([rank, option]);
  }
  // Stable within a rank, so each list's own order (e.g. local cities first) is kept.
  return ranked
    .map(([rank, option], i) => ({ rank, option, i }))
    .sort((a, b) => a.rank - b.rank || a.i - b.i)
    .slice(0, limit)
    .map((r) => r.option);
}

/** City names to suggest: those in the chosen country, or every city when it isn't one we know. */
export function cityOptions(country: string): string[] {
  const c = country.trim().toLowerCase();
  const inCountry = CITIES.filter((x) => x.country.toLowerCase() === c);
  return [...new Set((inCountry.length ? inCountry : CITIES).map((x) => x.city))];
}
